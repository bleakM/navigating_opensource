#!/usr/bin/env python3
"""Reuse Grove's world builder; keep all truth products in the offline audit folder."""
import importlib.util
import json
import os
import xml.etree.ElementTree as ET
from pathlib import Path

import mujoco
import numpy as np
from PIL import Image
from scipy import ndimage
import yaml

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / 'third_party/grove-g1/workspace/src/g1_bringup'


def main():
    spec = importlib.util.spec_from_file_location('grove_world_builder', UPSTREAM/'tools/build_world.py')
    builder = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(builder)
    plan = yaml.safe_load((ROOT/'g1/scenes/apartment.yaml').read_text())
    manifest = yaml.safe_load((builder.ASSETS/'manifest.yaml').read_text())['assets']
    props = [builder.Prop(room, entry, manifest) for room, entries in plan['props'].items() for entry in entries]
    builder.rest_on_supports(props, plan, manifest)
    xml = builder.scene_xml(plan, props, manifest, builder.PLACEHOLDER)
    # Keep the original textured furniture, but use a practical software-rendered
    # RGB-D resolution. CameraInfo is generated by Grove from these actual sizes.
    tree = ET.fromstring(xml)
    for camera in tree.findall('.//camera'):
        if camera.get('name') in ('d435i','chest_d435i'):
            camera.set('resolution','424 240')
    visual = tree.find('visual')
    quality = visual.find('quality')
    if quality is None:
        quality = ET.SubElement(visual,'quality')
    quality.set('offsamples','0')
    quality.set('shadowsize','512')
    xml = ET.tostring(tree,encoding='unicode').replace('<include file="g1_29dof.xml" />','<include file="g1_29dof.xml"/>')
    (ROOT/'g1/scenes/g1_apartment_scene.xml').write_text(xml)
    model = mujoco.MjModel.from_xml_string(builder.standalone(xml))
    data = mujoco.MjData(model)
    mujoco.mj_forward(model,data)
    occupied,free,origin,centres = builder.occupancy(model,data,plan)
    # This map is for offline geometry review only. No launch loads this path.
    builder.MAPS = ROOT/'g1/audit'
    builder.write_map(occupied,free,origin,'apartment-truth')
    clearance = ndimage.distance_transform_edt(~occupied)*builder.MAP_RESOLUTION_M
    labels,_ = ndimage.label(clearance > 0.48)
    component = labels[builder.spawn_cell(origin)]
    assert component, 'Spawn is not clear for G1'
    reachable = labels == component
    rooms = {}
    for room in plan['rooms']:
        (x0,y0),(x1,y1) = room['rect']
        inside = ((centres[0][None,:]>x0)&(centres[0][None,:]<x1)
                  &(centres[1][:,None]>y0)&(centres[1][:,None]<y1))
        rooms[room['id']] = int(np.sum(reachable&inside))
        assert rooms[room['id']] > 100, f'G1 cannot reach room {room["id"]}'
    assert not np.any(reachable[[0,-1],:]) and not np.any(reachable[:,[0,-1]]), 'Exterior leak'
    sensor = yaml.safe_load((UPSTREAM/'config/sim_sensors.yaml').read_text())
    sensor['object_bodies'] = []  # Do not send scene objects as perception.
    (ROOT/'g1/config/sim_sensors_apartment.yaml').write_text(yaml.safe_dump(sensor,sort_keys=False))
    report = {'floor_area_m2':168,'functional_rooms':3,'props':len(props),
              'meshes':model.nmesh,'geoms':model.ngeom,'robot_radius_audit_m':.48,
              'reachable_room_cells':rooms,'truth_used_for_navigation':False}
    (ROOT/'g1/audit/scene-check.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))
    # Show the actual textured MuJoCo scene, without altering any robot state.
    with mujoco.Renderer(model,height=900,width=1200) as renderer:
        camera = mujoco.MjvCamera()
        camera.type = mujoco.mjtCamera.mjCAMERA_FREE
        camera.lookat[:] = [2.,0.,0.]
        camera.distance = 22
        camera.azimuth = 130
        camera.elevation = -65
        option = mujoco.MjvOption()
        option.geomgroup[3:] = 0
        renderer.update_scene(data,camera=camera,scene_option=option)
        Image.fromarray(renderer.render()).save(ROOT/'g1/audit/apartment-preview.png')


if __name__ == '__main__':
    main()
